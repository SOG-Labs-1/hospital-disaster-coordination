function inside([x, y]: [number, number], poly: [number, number][]) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i]!, [xj, yj] = poly[j]!;
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

export const project = (lon: number, lat: number, k: number) => ({ x: (lon - 127) * k, y: (46 - lat) * k * 1.22 });

/** 輪郭の内側に入る格子点（経度・緯度の刻み step） */
export function dots(step: number) {
  const out: { lon: number; lat: number }[] = [];
  for (let lat = 25.6; lat <= 45.8; lat += step) {
    for (let lon = 127; lon <= 146; lon += step) {
      if (islands.some((p) => inside([lon, lat], p))) out.push({ lon, lat });
    }
  }
  // 沖縄のように小さい島は格子にかからないので、点を1つ足す
  out.push({ lon: 127.9, lat: 26.5 });
  return out;
}
